//! Bounded, allocation-free selector for ath10k API-2 `board-2.bin` data.
//!
//! The caller supplies the board-name candidates in source order. This module
//! parses only the outer/inner IE framing and returns a borrowed view of the
//! matching board payload; it does not copy, decode, or authorize firmware.

const BOARD_MAGIC: &[u8] = b"QCA-ATH10K-BOARD\0";
const BOARD_MAGIC_PADDED_BYTES: usize = 20;
const IE_HEADER_BYTES: usize = 8;
const IE_BOARD: u32 = 0;
const IE_BOARD_EXT: u32 = 1;
const IE_BOARD_NAME: u32 = 0;
const IE_BOARD_DATA: u32 = 1;
const BOARD_NAME_CAPACITY: usize = 100;
const BDF_VARIANT_CAPACITY: usize = 0x20;

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum BoardFileError {
    FileTooShort,
    InvalidMagic,
    EmptyName,
    InvalidVariant,
    NameTooLong,
    LengthOverflow,
    IePayloadTruncated,
    IePaddingTruncated,
    NoMatchingEntry,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum BoardIeKind {
    Board,
    BoardExt,
}

impl BoardIeKind {
    const fn id(self) -> u32 {
        match self {
            Self::Board => IE_BOARD,
            Self::BoardExt => IE_BOARD_EXT,
        }
    }
}

/// A borrowed match from the board-2 container.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct BoardData<'a> {
    /// Index into the caller's ordered candidate-name list.
    pub candidate_index: usize,
    pub kind: BoardIeKind,
    /// Payload bytes from the `ATH10K_BD_IE_BOARD_DATA` element.
    pub bytes: &'a [u8],
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
struct BoardName {
    bytes: [u8; BOARD_NAME_CAPACITY],
    len: usize,
}

impl BoardName {
    const fn empty() -> Self {
        Self {
            bytes: [0; BOARD_NAME_CAPACITY],
            len: 0,
        }
    }

    fn push(&mut self, bytes: &[u8]) -> Result<(), BoardFileError> {
        let end = self
            .len
            .checked_add(bytes.len())
            .ok_or(BoardFileError::LengthOverflow)?;
        // Linux formats into a 100-byte C buffer, reserving one byte for NUL.
        if end >= BOARD_NAME_CAPACITY {
            return Err(BoardFileError::NameTooLong);
        }
        self.bytes[self.len..end].copy_from_slice(bytes);
        self.len = end;
        Ok(())
    }

    fn push_hex_u32(&mut self, value: u32) -> Result<(), BoardFileError> {
        const HEX: &[u8; 16] = b"0123456789abcdef";
        let mut value = value;
        let mut reversed = [0; 8];
        let mut digits = 0;
        loop {
            reversed[digits] = HEX[(value & 0xf) as usize];
            digits += 1;
            value >>= 4;
            if value == 0 {
                break;
            }
        }
        while digits != 0 {
            digits -= 1;
            self.push(&reversed[digits..digits + 1])?;
        }
        Ok(())
    }

    fn as_bytes(&self) -> &[u8] {
        &self.bytes[..self.len]
    }
}

/// Sunfish SNOC board-name candidates generated by ath10k's QMI-ID path.
///
/// The order is the pinned Linux order: variant plus both IDs, both IDs
/// without a variant, then board ID only. The caller must provide the runtime
/// QMI IDs; this helper does not guess them.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct SnocQmiBoardNames {
    names: [BoardName; 3],
}

impl SnocQmiBoardNames {
    pub fn new(
        board_id: u32,
        chip_id: u32,
        variant: Option<&[u8]>,
    ) -> Result<Self, BoardFileError> {
        let variant = variant.unwrap_or_default();
        if variant.len() >= BDF_VARIANT_CAPACITY || variant.contains(&0) {
            return Err(BoardFileError::InvalidVariant);
        }

        let with_ids = |include_variant: bool| -> Result<BoardName, BoardFileError> {
            let mut name = BoardName::empty();
            name.push(b"bus=snoc,qmi-board-id=")?;
            name.push_hex_u32(board_id)?;
            name.push(b",qmi-chip-id=")?;
            name.push_hex_u32(chip_id)?;
            if include_variant && !variant.is_empty() {
                name.push(b",variant=")?;
                name.push(variant)?;
            }
            Ok(name)
        };

        let mut board_only = BoardName::empty();
        board_only.push(b"bus=snoc,qmi-board-id=")?;
        board_only.push_hex_u32(board_id)?;

        Ok(Self {
            names: [with_ids(true)?, with_ids(false)?, board_only],
        })
    }

    pub fn as_bytes(&self) -> [&[u8]; 3] {
        [
            self.names[0].as_bytes(),
            self.names[1].as_bytes(),
            self.names[2].as_bytes(),
        ]
    }
}

/// Select one exact board entry from API-2 `board-2.bin` bytes.
///
/// This follows the pinned ath10k parser's four-byte IE alignment, exact
/// board-name comparison, and first matching name-then-data behavior. As in
/// Linux, an incomplete final tail of at most one IE header is ignored.
pub fn find_board_data<'a>(
    file: &'a [u8],
    board_name: &[u8],
    kind: BoardIeKind,
) -> Result<BoardData<'a>, BoardFileError> {
    find_board_data_with_fallback(file, &[board_name], kind)
}

/// Try exact board names in caller-provided priority order.
pub fn find_board_data_with_fallback<'a>(
    file: &'a [u8],
    board_names: &[&[u8]],
    kind: BoardIeKind,
) -> Result<BoardData<'a>, BoardFileError> {
    if file.len() < BOARD_MAGIC_PADDED_BYTES {
        return Err(BoardFileError::FileTooShort);
    }
    if file.get(..BOARD_MAGIC.len()) != Some(BOARD_MAGIC) {
        return Err(BoardFileError::InvalidMagic);
    }
    if board_names.is_empty() || board_names.iter().any(|name| name.is_empty()) {
        return Err(BoardFileError::EmptyName);
    }

    for (candidate_index, board_name) in board_names.iter().enumerate() {
        if let Some(bytes) = find_in_file(file, board_name, kind)? {
            return Ok(BoardData {
                candidate_index,
                kind,
                bytes,
            });
        }
    }
    Err(BoardFileError::NoMatchingEntry)
}

/// Apply Linux's Sunfish SNOC QMI candidate order for the main board data.
///
/// Extended board data uses the separate BMI eboard identity in Linux and
/// must be selected through `find_board_data_with_fallback` with that name.
pub fn find_snoc_qmi_board_data<'a>(
    file: &'a [u8],
    board_id: u32,
    chip_id: u32,
    variant: Option<&[u8]>,
) -> Result<BoardData<'a>, BoardFileError> {
    let names = SnocQmiBoardNames::new(board_id, chip_id, variant)?;
    find_board_data_with_fallback(file, &names.as_bytes(), BoardIeKind::Board)
}

fn find_in_file<'a>(
    file: &'a [u8],
    board_name: &[u8],
    kind: BoardIeKind,
) -> Result<Option<&'a [u8]>, BoardFileError> {
    let mut offset = BOARD_MAGIC_PADDED_BYTES;
    while file.len().saturating_sub(offset) > IE_HEADER_BYTES {
        let (id, data, next) = read_ie(file, offset)?;
        if id == kind.id() {
            if let Some(found) = find_in_board_ie(data, board_name)? {
                return Ok(Some(found));
            }
        }
        offset = next;
    }
    Ok(None)
}

fn find_in_board_ie<'a>(
    bytes: &'a [u8],
    wanted_name: &[u8],
) -> Result<Option<&'a [u8]>, BoardFileError> {
    let mut offset = 0;
    let mut name_matched = false;
    while bytes.len().saturating_sub(offset) > IE_HEADER_BYTES {
        let (id, data, next) = read_ie(bytes, offset)?;
        match id {
            IE_BOARD_NAME if data == wanted_name => name_matched = true,
            IE_BOARD_DATA if name_matched => return Ok(Some(data)),
            _ => {}
        }
        offset = next;
    }
    Ok(None)
}

fn read_ie(bytes: &[u8], offset: usize) -> Result<(u32, &[u8], usize), BoardFileError> {
    let header_end = offset
        .checked_add(IE_HEADER_BYTES)
        .ok_or(BoardFileError::LengthOverflow)?;
    let header = bytes
        .get(offset..header_end)
        .ok_or(BoardFileError::IePayloadTruncated)?;
    let id = u32::from_le_bytes([header[0], header[1], header[2], header[3]]);
    let payload_len = u32::from_le_bytes([header[4], header[5], header[6], header[7]]) as usize;
    let payload_end = header_end
        .checked_add(payload_len)
        .ok_or(BoardFileError::LengthOverflow)?;
    let data = bytes
        .get(header_end..payload_end)
        .ok_or(BoardFileError::IePayloadTruncated)?;
    let padded_len = payload_len
        .checked_add(3)
        .ok_or(BoardFileError::LengthOverflow)?
        & !3;
    let next = header_end
        .checked_add(padded_len)
        .ok_or(BoardFileError::LengthOverflow)?;
    if next > bytes.len() {
        return Err(BoardFileError::IePaddingTruncated);
    }
    Ok((id, data, next))
}
